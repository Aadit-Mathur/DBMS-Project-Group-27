-- =====================================================================
-- Seller & Products module: SELLER, CATEGORY, PRODUCT
-- Target: PostgreSQL 14+ (Neon)
--
-- Safe to run on a fresh database AND on the team's existing Neon
-- tables, and safe to run more than once:
--   * tables are created only if they do not exist
--   * a constraint is added only if an equivalent one is missing
--   * trigger, view and function are (re)created
-- Everything runs in one transaction: if any step fails (for example
-- existing data breaks a new CHECK), nothing is changed.
--
-- Run:  python db/run_sql.py db/seller_product_schema.sql
-- Run this BEFORE the ordering tables (ORDER_ITEM references PRODUCT).
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Tables (fresh database only; existing tables are left as they are)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS seller (
    seller_id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL,
    email              VARCHAR(255) NOT NULL,
    phone              VARCHAR(15)  NOT NULL,
    registration_date  DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS category (
    category_id    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name  VARCHAR(100) NOT NULL,
    description    TEXT
);

CREATE TABLE IF NOT EXISTS product (
    product_id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          BIGINT        NOT NULL,
    category_id        BIGINT        NOT NULL,
    product_name       VARCHAR(200)  NOT NULL,
    description        TEXT,
    brand              VARCHAR(100),
    price              NUMERIC(10,2) NOT NULL,
    quantity_in_stock  INT           NOT NULL DEFAULT 0,
    reorder_level      INT           NOT NULL DEFAULT 10,
    last_updated       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- 2. Columns and defaults this module needs on existing tables
-- ---------------------------------------------------------------------
-- Delisting: a product that has been ordered cannot be deleted
-- (order_item FK), so it is hidden with is_active = FALSE instead.
ALTER TABLE product ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE product ALTER COLUMN seller_id         SET NOT NULL;   -- total participation in LISTS
ALTER TABLE product ALTER COLUMN category_id       SET NOT NULL;   -- total participation in CONTAINS
ALTER TABLE product ALTER COLUMN price             SET NOT NULL;
ALTER TABLE product ALTER COLUMN quantity_in_stock SET DEFAULT 0;
ALTER TABLE product ALTER COLUMN quantity_in_stock SET NOT NULL;
ALTER TABLE product ALTER COLUMN reorder_level     SET DEFAULT 10;
ALTER TABLE product ALTER COLUMN reorder_level     SET NOT NULL;
ALTER TABLE product ALTER COLUMN last_updated      SET DEFAULT CURRENT_TIMESTAMP;

-- ---------------------------------------------------------------------
-- 3. UNIQUE constraints (candidate keys) - added only if no unique
--    constraint/index already covers exactly these columns
-- ---------------------------------------------------------------------
DO $$
DECLARE
    r       record;
    present boolean;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('seller',   ARRAY['email'],                    'uq_seller_email'),
            ('seller',   ARRAY['phone'],                    'uq_seller_phone'),
            ('category', ARRAY['category_name'],            'uq_category_name'),
            ('product',  ARRAY['seller_id','product_name'], 'uq_product_seller_name')
        ) AS v(tbl, cols, conname)
    LOOP
        SELECT EXISTS (
            SELECT 1
            FROM   pg_index i
            WHERE  i.indrelid = r.tbl::regclass
              AND  i.indisunique
              AND  i.indpred IS NULL
              AND  (SELECT array_agg(a.attname::text ORDER BY a.attname::text)
                    FROM   pg_attribute a
                    WHERE  a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey))
                 = (SELECT array_agg(c ORDER BY c) FROM unnest(r.cols) AS c)
        ) INTO present;

        IF present THEN
            RAISE NOTICE 'kept existing UNIQUE on %(%)', r.tbl, array_to_string(r.cols, ', ');
        ELSE
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I UNIQUE (%s)',
                           r.tbl, r.conname,
                           (SELECT string_agg(quote_ident(c), ', ') FROM unnest(r.cols) AS c));
            RAISE NOTICE 'added %', r.conname;
        END IF;
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- 4. CHECK constraints (business rules), using the team's chk_ rules:
--      price >= 0, stock >= 0, reorder level >= 0,
--      phone = 10 to 15 digits, email = basic x@y.z format
--    Earlier versions of this script used ck_ names with stricter price
--    and phone rules; those are renamed or dropped here so that each rule
--    exists exactly once. A rule already present under another name with
--    the same definition is kept and not duplicated.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    r       record;
    added   boolean;
    twin    text;
BEGIN
    -- the email rule only existed in this module: keep it, team naming
    IF EXISTS (SELECT 1 FROM pg_constraint
               WHERE conrelid = 'seller'::regclass AND conname = 'ck_seller_email')
       AND NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conrelid = 'seller'::regclass AND conname = 'chk_seller_email') THEN
        ALTER TABLE seller RENAME CONSTRAINT ck_seller_email TO chk_seller_email;
        RAISE NOTICE 'renamed ck_seller_email to chk_seller_email';
    END IF;

    -- retire this module's earlier ck_ rules in favour of the team's
    FOR r IN
        SELECT * FROM (VALUES
            ('seller',  'ck_seller_email'),
            ('seller',  'ck_seller_phone'),
            ('product', 'ck_product_price'),
            ('product', 'ck_product_stock'),
            ('product', 'ck_product_reorder')
        ) AS v(tbl, conname)
    LOOP
        IF EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = r.tbl::regclass AND conname = r.conname) THEN
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', r.tbl, r.conname);
            RAISE NOTICE 'dropped old %', r.conname;
        END IF;
    END LOOP;

    FOR r IN
        SELECT * FROM (VALUES
            ('seller',  'chk_seller_email',          $c$email LIKE '%_@_%._%'$c$),
            ('seller',  'chk_seller_phone',          $c$phone ~ '^[0-9]{10,15}$'$c$),
            ('product', 'chk_product_price',         'price >= 0'),
            ('product', 'chk_product_stock',         'quantity_in_stock >= 0'),
            ('product', 'chk_product_reorder_level', 'reorder_level >= 0')
        ) AS v(tbl, conname, expr)
    LOOP
        added := false;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conrelid = r.tbl::regclass AND conname = r.conname) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I CHECK (%s)', r.tbl, r.conname, r.expr);
            added := true;
        END IF;

        -- same rule already present under another name?
        SELECT other.conname INTO twin
        FROM   pg_constraint mine
        JOIN   pg_constraint other
               ON  other.conrelid = mine.conrelid
               AND other.contype  = 'c'
               AND other.conname <> mine.conname
               AND pg_get_constraintdef(other.oid) = pg_get_constraintdef(mine.oid)
        WHERE  mine.conrelid = r.tbl::regclass AND mine.conname = r.conname
        ORDER  BY other.conname
        LIMIT  1;

        IF twin IS NOT NULL AND added THEN
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', r.tbl, r.conname);
            RAISE NOTICE 'kept existing equivalent CHECK % (no duplicate %)', twin, r.conname;
        ELSIF added THEN
            RAISE NOTICE 'added %', r.conname;
        ELSE
            RAISE NOTICE 'kept %', r.conname;
        END IF;
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- 5. Foreign keys: ON DELETE RESTRICT, so a seller or category that
--    still has products cannot be deleted. An existing FK is kept,
--    unless it cascades or nulls on delete, in which case it is
--    replaced (cascading would silently delete products).
-- ---------------------------------------------------------------------
DO $$
DECLARE
    r        record;
    existing record;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('product', 'seller_id',   'seller',   'seller_id',   'fk_product_seller'),
            ('product', 'category_id', 'category', 'category_id', 'fk_product_category')
        ) AS v(tbl, col, ref_tbl, ref_col, conname)
    LOOP
        SELECT c.conname, c.confdeltype INTO existing
        FROM   pg_constraint c
        WHERE  c.contype   = 'f'
          AND  c.conrelid  = r.tbl::regclass
          AND  c.confrelid = r.ref_tbl::regclass
          AND  c.conkey    = ARRAY[(SELECT attnum FROM pg_attribute
                                    WHERE attrelid = r.tbl::regclass AND attname = r.col)]
        LIMIT 1;

        IF FOUND THEN
            IF existing.confdeltype IN ('a', 'r') THEN            -- NO ACTION / RESTRICT
                RAISE NOTICE 'kept existing FK % (blocks deletes)', existing.conname;
                CONTINUE;
            END IF;
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', r.tbl, existing.conname);
            RAISE NOTICE 'replaced FK % (it cascaded or nulled on delete)', existing.conname;
        END IF;

        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES %I (%I) '
                       'ON DELETE RESTRICT ON UPDATE CASCADE',
                       r.tbl, r.conname, r.col, r.ref_tbl, r.ref_col);
        RAISE NOTICE 'added %', r.conname;
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- 6. Indexes
--    (seller_id) is already covered by the UNIQUE (seller_id, product_name)
--    index, whose first column is seller_id, so no separate index.
-- ---------------------------------------------------------------------
-- customer browsing: "products in category X between price A and B"
CREATE INDEX IF NOT EXISTS idx_product_category_price ON product (category_id, price);

-- seller dashboard: low-stock alerts; partial index stays small
CREATE INDEX IF NOT EXISTS idx_product_low_stock ON product (seller_id)
    WHERE is_active AND quantity_in_stock <= reorder_level;

-- ---------------------------------------------------------------------
-- 7. Trigger: keep last_updated correct on every change to a product
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_product_touch()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.last_updated := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_product_touch ON product;
CREATE TRIGGER trg_product_touch
BEFORE UPDATE ON product
FOR EACH ROW
EXECUTE FUNCTION fn_product_touch();

-- ---------------------------------------------------------------------
-- 8. View: active products at or below their reorder level
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS v_low_stock_products;
CREATE VIEW v_low_stock_products AS
SELECT p.product_id,
       p.product_name,
       s.seller_id,
       s.name                                AS seller_name,
       c.category_name,
       p.quantity_in_stock,
       p.reorder_level,
       p.reorder_level - p.quantity_in_stock AS shortfall
FROM   product  p
JOIN   seller   s ON s.seller_id   = p.seller_id
JOIN   category c ON c.category_id = p.category_id
WHERE  p.is_active
  AND  p.quantity_in_stock <= p.reorder_level;

-- ---------------------------------------------------------------------
-- 9. Function: restock a product, only if it belongs to that seller
--    SELECT restock_product(seller_id, product_id, qty);  -> new stock
--    Errors: qty <= 0 -> check_violation (23514)
--            not the seller's product -> insufficient_privilege (42501)
-- ---------------------------------------------------------------------
DROP FUNCTION IF EXISTS restock_product(INT, INT, INT);
CREATE OR REPLACE FUNCTION restock_product(p_seller_id  BIGINT,
                                           p_product_id BIGINT,
                                           p_qty        INT)
RETURNS INT
LANGUAGE plpgsql AS $$
DECLARE
    v_new_stock INT;
BEGIN
    IF p_qty IS NULL OR p_qty <= 0 THEN
        RAISE EXCEPTION 'Restock quantity must be positive (got %)', p_qty
            USING ERRCODE = 'check_violation';
    END IF;

    UPDATE product
    SET    quantity_in_stock = quantity_in_stock + p_qty
    WHERE  product_id = p_product_id
      AND  seller_id  = p_seller_id
    RETURNING quantity_in_stock INTO v_new_stock;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % does not belong to seller %', p_product_id, p_seller_id
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    RETURN v_new_stock;
END;
$$;

COMMIT;
